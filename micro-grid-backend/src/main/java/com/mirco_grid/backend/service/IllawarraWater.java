    /** Bounding box per ring, so the usual case costs four comparisons. */
    private static final double[][] INLAND_BOUNDS = new double[INLAND_WATER.length][];

    static {
        for (int i = 0; i < INLAND_WATER.length; i++) {
            double[] ring = INLAND_WATER[i];
            double south = Double.MAX_VALUE, north = -Double.MAX_VALUE;
            double west = Double.MAX_VALUE, east = -Double.MAX_VALUE;
            for (int j = 0; j < ring.length; j += 2) {
                south = Math.min(south, ring[j]);
                north = Math.max(north, ring[j]);
                west = Math.min(west, ring[j + 1]);
                east = Math.max(east, ring[j + 1]);
            }
            INLAND_BOUNDS[i] = new double[] {south, north, west, east};
        }
    }

    private IllawarraWater() {}

    /** True for open sea, and for the lagoons and harbours behind the shore. */
    public static boolean isWater(double lat, double lng) {
        if (lng >= coastLngAt(lat)) {
            return true;
        }
        for (int i = 0; i < INLAND_WATER.length; i++) {
            double[] b = INLAND_BOUNDS[i];
            if (lat < b[0] || lat > b[1] || lng < b[2] || lng > b[3]) {
                continue;
            }
            if (inRing(lat, lng, INLAND_WATER[i])) {
                return true;
            }
        }
        return false;
    }

    /** Longitude of the shore at a latitude, linearly interpolated. */
    static double coastLngAt(double lat) {
        // COAST runs north to south, so latitude falls as the index rises.
        if (lat >= COAST[0]) {
            return COAST[1];
        }
        if (lat <= COAST[COAST.length - 2]) {
            return COAST[COAST.length - 1];
        }
        int low = 0;
        int high = COAST.length / 2 - 1;
        while (high - low > 1) {
            int mid = (low + high) >>> 1;
            if (COAST[mid * 2] > lat) {
                low = mid;
            } else {
                high = mid;
            }
        }
        double aLat = COAST[low * 2], aLng = COAST[low * 2 + 1];
        double bLat = COAST[high * 2], bLng = COAST[high * 2 + 1];
        double span = aLat - bLat;
        return span == 0 ? aLng : aLng + ((aLat - lat) / span) * (bLng - aLng);
    }

    /** Ray casting against a flat lat, lng ring. */
    private static boolean inRing(double lat, double lng, double[] ring) {
        boolean inside = false;
        int count = ring.length / 2;
        for (int i = 0, j = count - 1; i < count; j = i++) {
            double iLat = ring[i * 2], iLng = ring[i * 2 + 1];
            double jLat = ring[j * 2], jLng = ring[j * 2 + 1];
            if ((iLat > lat) != (jLat > lat)
                    && lng < ((jLng - iLng) * (lat - iLat)) / (jLat - iLat) + iLng) {
                inside = !inside;
            }
        }
        return inside;
    }
